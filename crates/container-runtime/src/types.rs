impl PanelRef {
    pub fn validate(&self) -> Result<(), String> {
        if self.id.trim().is_empty()
            || self.id.starts_with('/')
            || self.id.contains('\\')
            || self.id.chars().any(char::is_control)
            || self
                .id
                .split('/')
                .any(|part| part.is_empty() || matches!(part, "." | ".."))
        {
            return Err("panel `id` must be a safe relative catalog identifier".into());
        }
        if !self.digest.starts_with("sha256:")
            || self.digest.len() != 71
            || !self.digest.as_bytes()[7..]
                .iter()
                .all(u8::is_ascii_hexdigit)
        {
            return Err(format!("panel `{}` has invalid digest", self.id));
        }
        if self.source.contains('\0') || self.source.trim() == "/" {
            return Err(format!("panel `{}` has invalid source", self.id));
        }
        if !Path::new(&self.mount_path).is_absolute()
            || self.mount_path == "/"
            || self.mount_path.contains('\\')
            || self.mount_path.chars().any(char::is_control)
            || self
                .mount_path
                .split('/')
                .skip(1)
                .any(|p| p.is_empty() || matches!(p, "." | ".."))
        {
            return Err(format!("panel `{}` has invalid mount path", self.id));
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn private_environment_accepts_only_one_nonempty_author_jwt() {
        assert!(
            PrivateEnvironment::new(vec![("OPENGWAS_JWT".into(), "synthetic-jwt".into())]).is_ok()
        );
        for values in [
            Vec::new(),
            vec![("OPENGWAS_TOKEN".into(), "synthetic-jwt".into())],
            vec![("OPENGWAS_JWT".into(), " ".into())],
            vec![("OPENGWAS_JWT".into(), "synthetic\njwt".into())],
            vec![
                ("OPENGWAS_JWT".into(), "synthetic-jwt".into()),
                ("OPENGWAS_JWT".into(), "synthetic-jwt".into()),
            ],
        ] {
            assert!(PrivateEnvironment::new(values).is_err());
        }
    }

    #[test]
    fn reference_identifiers_and_mounts_cannot_escape_their_namespace() {
        let panel = PanelRef {
            id: "publisher/panel".into(),
            digest: format!("sha256:{}", "a".repeat(64)),
            source: "/panels/approved".into(),
            mount_path: "/panels/reference".into(),
        };
        panel.validate().unwrap();
        for id in [
            "/absolute",
            "../evidence",
            "owner/../evidence",
            "owner//panel",
            "owner/./panel",
            "owner\\panel",
            "owner\nvalue",
        ] {
            assert!(
                PanelRef {
                    id: id.into(),
                    ..panel.clone()
                }
                .validate()
                .is_err(),
                "{id}"
            );
        }
        for mount_path in ["/panels/../data", "/panels//data", "/panels/./data"] {
            assert!(
                PanelRef {
                    mount_path: mount_path.into(),
                    ..panel.clone()
                }
                .validate()
                .is_err()
            );
        }
        assert!(
            PanelRef {
                digest: format!("sha256:{}", "z".repeat(64)),
                ..panel
            }
            .validate()
            .is_err()
        );
    }

    #[test]
    fn legacy_none_parses_as_isolated_and_cluster_is_rejected() {
        assert_eq!(
            ContainerNetwork::parse("isolated").unwrap(),
            ContainerNetwork::Isolated
        );
        assert_eq!(
            ContainerNetwork::parse(" none ").unwrap(),
            ContainerNetwork::Isolated
        );
        assert_eq!(
            ContainerNetwork::parse("egress").unwrap(),
            ContainerNetwork::Egress
        );
        let cluster = ContainerNetwork::parse("cluster").unwrap_err();
        assert!(cluster.contains("removed with the k3s backend"));
        assert!(ContainerNetwork::parse("host").is_err());
    }

    #[test]
    fn gpu_requests_parse_the_three_spelling() {
        assert_eq!(GpuRequest::parse("all").unwrap(), GpuRequest::All);
        assert_eq!(GpuRequest::parse(" ALL ").unwrap(), GpuRequest::All);
        assert_eq!(GpuRequest::parse("2").unwrap(), GpuRequest::Count(2));
        assert_eq!(
            GpuRequest::parse("device=0,2").unwrap(),
            GpuRequest::Devices("0,2".into())
        );
        assert_eq!(
            GpuRequest::parse("device=GPU-62c5").unwrap(),
            GpuRequest::Devices("GPU-62c5".into())
        );
        assert_eq!(GpuRequest::parse("").unwrap_err(), "gpus cannot be empty");
        assert!(GpuRequest::parse("0").is_err());
        assert!(GpuRequest::parse("-1").is_err());
        assert!(GpuRequest::parse("device=").is_err());
        assert!(GpuRequest::parse("device=0,,2").is_err());
        assert!(GpuRequest::parse("device=0;rm").is_err());
        assert!(GpuRequest::parse("--foo").is_err());
    }

    #[test]
    fn gpu_requests_render_podman_values_only_when_set() {
        assert_eq!(GpuRequest::None.podman_value(), None);
        assert_eq!(GpuRequest::All.podman_value(), Some("all".into()));
        assert_eq!(GpuRequest::Count(1).podman_value(), Some("1".into()));
        assert_eq!(
            GpuRequest::Devices("0,3".into()).podman_value(),
            Some("device=0,3".into())
        );
    }
}
