use std::path::{Path, PathBuf};

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

/// An immutable reference-data bundle stored in the authoritative object VFS.
#[derive(Debug, Clone, PartialEq, Eq, JsonSchema, Deserialize, Serialize)]
pub struct PanelRef {
    pub id: String,
    pub digest: String,
    pub source: String,
    pub mount_path: String,
}

/// A panel materialized into the shared panel cache.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CachedPanel {
    pub id: String,
    pub digest: String,
    pub host_path: PathBuf,
    pub mount_path: String,
    /// Original manifest bytes verified by PanelCache, retained in memory.
    /// Cache directories contain only payload files and their completion marker.
    pub manifest_bytes: Option<Vec<u8>>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkspaceRef {
    pub host_path: PathBuf,
    pub container_workdir: String,
}

/// One host directory bind-mounted read-only at its own absolute path so
/// symlink-staged inputs resolve inside the container.
///
/// The container destination is always the identity of `host_dir`: staged
/// symlinks carry host-absolute targets, so mounting the source parent at
/// the same path makes them resolve unchanged.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InputMount {
    pub host_dir: PathBuf,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, JsonSchema, Deserialize, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum PullPolicy {
    #[default]
    Missing,
    Always,
    Newer,
    Never,
}

/// Network profile of an ephemeral container.
///
/// `Isolated` runs with no network devices at all (`podman --network none`).
/// `Egress` uses the host's default container networking.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, JsonSchema, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum ContainerNetwork {
    #[default]
    Isolated,
    Egress,
}

impl ContainerNetwork {
    /// Parse a spec-level network name. `none` is accepted as a legacy
    /// spelling of `isolated`; `cluster` was removed together with the k3s
    /// backend and is rejected explicitly.
    pub fn parse(value: &str) -> Result<Self, String> {
        match value.trim().to_ascii_lowercase().as_str() {
            "isolated" | "none" => Ok(Self::Isolated),
            "egress" => Ok(Self::Egress),
            "cluster" => Err(
                "network profile `cluster` was removed with the k3s backend; use `isolated` or `egress`"
                    .into(),
            ),
            other => Err(format!(
                "network must be `isolated` or `egress`; got `{other}`"
            )),
        }
    }
}

/// GPU passthrough request, rendered as Podman's `--gpus` value.
///
/// GPU access is strictly opt-in: the default adds no flag at all, so a
/// container sees GPUs only when its spec asks for them. The host must expose
/// the devices through the container device interface — for rootless Podman
/// that means the nvidia-container-toolkit CDI spec generated by
/// `nvidia-ctk cdi generate` — otherwise `podman create` fails.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub enum GpuRequest {
    /// No GPU passthrough (no `--gpus` flag).
    #[default]
    None,
    /// All host GPUs (`--gpus all`).
    All,
    /// The first `n` host GPUs (`--gpus n`).
    Count(u32),
    /// Specific devices by index or UUID (`--gpus device=0,2`).
    Devices(String),
}

impl GpuRequest {
    /// Parse a spec-level GPU request: `all`, a positive device count, or
    /// `device=<comma-separated indices or UUIDs>`.
    pub fn parse(value: &str) -> Result<Self, String> {
        let value = value.trim();
        if value.is_empty() {
            return Err("gpus cannot be empty".into());
        }
        if value.eq_ignore_ascii_case("all") {
            return Ok(Self::All);
        }
        if let Ok(count) = value.parse::<u32>() {
            if count == 0 {
                return Err("gpus count must be positive".into());
            }
            return Ok(Self::Count(count));
        }
        if let Some(ids) = value.strip_prefix("device=") {
            let valid = !ids.is_empty()
                && ids.split(',').all(|id| {
                    !id.is_empty() && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-')
                });
            if valid {
                return Ok(Self::Devices(ids.to_string()));
            }
            return Err(format!(
                "gpus device list must be comma-separated indices or UUIDs; got `{ids}`"
            ));
        }
        Err(format!(
            "gpus must be `all`, a positive count, or `device=<ids>`; got `{value}`"
        ))
    }

    /// The value passed to Podman's `--gpus` flag, or `None` when the request
    /// needs no flag.
    pub fn podman_value(&self) -> Option<String> {
        match self {
            Self::None => None,
            Self::All => Some("all".into()),
            Self::Count(count) => Some(count.to_string()),
            Self::Devices(ids) => Some(format!("device={ids}")),
        }
    }
}

pub struct PrivateEnvironment {
    values: Vec<(String, String)>,
}

impl PrivateEnvironment {
    pub fn new(values: Vec<(String, String)>) -> Result<Self, String> {
        let mut names = std::collections::BTreeSet::new();
        if values.is_empty()
            || values.iter().any(|(name, value)| {
                name != "OPENGWAS_JWT"
                    || !names.insert(name.clone())
                    || value.trim().is_empty()
                    || value.chars().any(char::is_control)
            })
        {
            return Err("invalid private container environment".into());
        }
        Ok(Self { values })
    }

    /// Sensitive values for trusted execution backends. Never serialize these
    /// into dispatches, diagnostics, argv, or permanent provenance records.
    pub fn values(&self) -> &[(String, String)] {
        &self.values
    }
}

