fn private_dir(path: &Path) -> SmokeResult<()> {
    std::fs::DirBuilder::new().mode(0o700).create(path)?;
    Ok(())
}

#[derive(Clone)]
struct RemoteBuiltinDescriptor(NodePorts);

#[async_trait::async_trait]
impl DagNode for RemoteBuiltinDescriptor {
    fn ports(&self) -> &NodePorts {
        &self.0
    }
    fn kind(&self) -> &'static str {
        "file_to_dataframe"
    }
    fn clone_box(&self) -> Box<dyn DagNode> {
        Box::new(self.clone())
    }
    fn as_any(&self) -> &dyn std::any::Any {
        self
    }
    async fn execute(
        &mut self,
        _: &NodeCtx,
        _: &[NodeInput],
        _: &NodeReporter,
    ) -> Result<dag_core::dag::graph::PortOutputs, DagError> {
        Err(DagError::Schedule(
            "warehouse descriptor must never execute locally".into(),
        ))
    }
}

// Deliberately forbid payload transfers. Mandatory JSON task manifests may be
// downloaded. Independent bounded output verification uses a separate store.
struct RetainedOnlyStore {
    inner: SshArtifactStore,
    upload_attempts: AtomicUsize,
    arrow_download_attempts: AtomicUsize,
}

#[async_trait::async_trait]
impl TaskArtifactStore for RetainedOnlyStore {
    async fn remote_input(
        &self,
        file: FileRef,
        storage: Option<&vfs::OpendalFileStorage>,
    ) -> Result<Option<FileRef>, DagError> {
        self.inner.remote_input(file, storage).await
    }
    async fn retained_reference(&self, file: FileRef) -> Result<Option<FileRef>, DagError> {
        self.inner.retained_reference(file).await
    }
    async fn upload(&self, _: FileRef, _: &str, _: &str) -> Result<FileRef, DagError> {
        self.upload_attempts.fetch_add(1, Ordering::SeqCst);
        Err(DagError::Schedule(
            "warehouse smoke forbids coordinator payload uploads".into(),
        ))
    }
    async fn download(&self, file: FileRef, task: &str, name: &str) -> Result<FileRef, DagError> {
        if file.format.as_deref() == Some("arrow") || file.path.ends_with(".arrow") {
            self.arrow_download_attempts.fetch_add(1, Ordering::SeqCst);
            return Err(DagError::Schedule(
                "warehouse smoke forbids coordinator Arrow downloads".into(),
            ));
        }
        self.inner.download(file, task, name).await
    }
}

fn policy(root: &str, ssh: Option<(&str, &str)>) -> String {
    let backend = match ssh {
        Some((alias, python)) => format!(
            "type = \"ssh\"\nalias = {}\npython = {}\n",
            json!(alias),
            json!(python)
        ),
        None => "type = \"local\"\n".into(),
    };
    let mut text = format!(
        "[[backend]]\nid = \"warehouse\"\nroot = {}\n{backend}",
        json!(root)
    );
    for (path, source, uid) in [
        ("/warehouse-account", "", 0),
        ("/warehouse-public", "public", 12345),
        ("/warehouse-private", "private", 0),
        ("/warehouse-runs", "runs", 12345),
    ] {
        // The broad account mount is needed only for coordinator mapping
        // validation. The worker does not expose that physical root.
        if ssh.is_none() && path == "/warehouse-account" {
            continue;
        }
        text.push_str(&format!(
            "\n[[mount]]\npath = {}\nbackend = \"warehouse\"\nsource = {}\nread_only = true\npermissions = {{mode=\"0700\",file_mode=\"0600\",directory_mode=\"0700\",owner={{uid={uid},gid={uid}}}}}\n",
            json!(path), json!(source),
        ));
    }
    text
}

async fn python(
    ssh: &SshTarget,
    executable: &str,
    code: &str,
    evidence: &Path,
) -> SmokeResult<Value> {
    // code is generated by this frozen test; user values are JSON strings.
    let result = capture(
        ssh,
        &format!(
            "{} -B - <<'AUTONOMICS_WAREHOUSE_PY'\n{code}\nAUTONOMICS_WAREHOUSE_PY",
            quote(executable)
        ),
        evidence,
    )
    .await?;
    if result["exit_code"] != 0 {
        return Err("warehouse remote helper failed; retain all evidence".into());
    }
    Ok(serde_json::from_str(
        result["stdout"].as_str().ok_or("missing helper stdout")?,
    )?)
}

async fn provision(profile: &Profile, fixture: &str, worker_policy: &str) -> SmokeResult<()> {
    let settings = profile
        .warehouse
        .as_ref()
        .ok_or("missing warehouse settings")?;
    if !clean_absolute(Path::new(&settings.remote_python)) {
        return Err("explicit absolute warehouse Python required".into());
    }
    let payload = serde_json::to_string(&json!({"root":fixture,"policy":worker_policy}))?;
    let code = format!(
        r#"import os,stat,json,hashlib
p=json.loads({literal})
root=p['root']; parts=root.split('/')[1:]
assert len(parts)>2 and all(x not in ('','.','..') for x in parts)
fd=os.open('/',os.O_PATH|os.O_DIRECTORY)
for part in parts[:-1]:
 n=os.open(part,os.O_PATH|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=fd);os.close(fd);fd=n
os.mkdir(parts[-1],0o700,dir_fd=fd)
n=os.open(parts[-1],os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=fd);os.close(fd);fd=n
s=os.fstat(fd);assert s.st_uid==os.geteuid() and stat.S_IMODE(s.st_mode)==0o700
for name in ('public','private','runs'):os.mkdir(name,0o700,dir_fd=fd)
def write(parent,name,body):
 f=os.open(name,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600,dir_fd=parent)
 with os.fdopen(f,'wb') as out:out.write(body);out.flush();os.fsync(out.fileno())
csv=b'id,label\n1,alpha\n2,beta\n3,gamma\n'
for name in ('public','private'):
 d=os.open(name,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=fd)
 write(d,'values.csv',csv);os.fsync(d);os.close(d)
write(fd,'worker-vfs.toml',p['policy'].encode());os.fsync(fd);os.close(fd)
print(json.dumps({{'fixture_root':root,'uid':s.st_uid,'device':s.st_dev,'inode':s.st_ino,'mode':'0700','worker_vfs_sha256':hashlib.sha256(p['policy'].encode()).hexdigest(),'csv_sha256':hashlib.sha256(csv).hexdigest()}}))
"#,
        literal = serde_json::to_string(&payload)?
    );
    let ssh = SshTarget::new(&profile.ssh_program, &profile.ssh_host)
        .with_command_timeout(Duration::from_secs(60));
    let result = python(
        &ssh,
        &settings.remote_python,
        &code,
        &profile.local_root.join("PROVISION.json"),
    )
    .await?;
    if result["fixture_root"] != fixture
        || result["worker_vfs_sha256"] != format!("{:x}", Sha256::digest(worker_policy.as_bytes()))
    {
        return Err("warehouse provisioning identity mismatch".into());
    }
    Ok(())
}

fn data_home(profile: &Profile, fixture: &str) -> SshDataHome {
    SshDataHome {
        ssh_aliases: vec![profile.ssh_host.clone()],
        remote_root: fixture.into(),
        vfs_prefix: "/warehouse-account".into(),
        retained_remote_root: Some(profile.remote_scratch_root.clone()),
        retained_vfs_prefix: Some("/warehouse-runs".into()),
    }
}

fn context(profile: &Profile, fixture: &str, principal: VfsPrincipal) -> SmokeResult<Arc<NodeCtx>> {
    let manifest = vfs::VfsManifest::from_toml(&policy(
        fixture,
        Some((
            &profile.ssh_host,
            &profile.warehouse.as_ref().unwrap().remote_python,
        )),
    ))?;
    private_json(&profile.local_root.join("COORDINATOR_VFS.json"), &manifest)?;
    let mounts = Arc::new(
        vfs::MountedObjectStore::from_manifest(&manifest)?.with_principal(principal.clone()),
    );
    let object_root = profile.local_root.join("objects");
    private_dir(&object_root)?;
    let operator_storage = vfs::OpendalFileStorage::with_mounts(&object_root, mounts);
    // Deployment validates the restricted account mapping as operator before
    // issuing a scoped session view. The agent cannot read that broad mount.
    data_home(profile, fixture).validate_vfs(&operator_storage)?;
    let storage = Arc::new(operator_storage.with_principal(principal));
    storage.check_readable("/warehouse-public/values.csv")?;
    if storage
        .check_readable("/warehouse-private/values.csv")
        .is_ok()
    {
        return Err("private coordinator mount is not denied".into());
    }
    let session = SessionContext::new();
    session
        .runtime_env()
        .register_object_store(ObjectStoreUrl::parse("vfs://")?.as_ref(), storage.clone());
    Ok(Arc::new(NodeCtx::new(session.runtime_env(), Some(storage))))
}

fn resources() -> TaskResources {
    TaskResources {
        cpus: Some(1),
        memory_bytes: Some(1 << 30),
        max_duration_ms: Some(120000),
    }
}

fn read_task(label: &str, path: &str, ctx: Arc<NodeCtx>) -> TaskExecution {
    TaskExecution {
        node: Box::new(RemoteBuiltinDescriptor(
            NodePorts::new().add_output_port_of_type(None, PortType::DataFrame),
        )),
        submission: TaskSubmission {
            spec: TaskSpec {
                id: label.into(),
                kind: "core/file_to_dataframe".into(),
                spec: json!({"path":path,"format":"csv"}),
                logical_node: None,
                item_key: None,
                item: None,
                inputs: vec![],
                outputs: vec![TaskOutputBinding {
                    name: "table".into(),
                    port: 0,
                    payload: "dataframe".into(),
                    artifact_paths: vec![],
                }],
            },
            inputs: vec![],
            resources: resources(),
        },
        engine_ctx: ctx,
        reporter: NodeReporter::noop(),
        cancellation: CancellationToken::new(),
    }
}

async fn execute(
    profile: &Profile,
    fixture: &str,
    label: &str,
    execution: TaskExecution,
) -> SmokeResult<(JobResult, TaskAttemptReceipt, TaskLease)> {
    let root = profile.local_root.join(label);
    private_dir(&root)?;
    for name in ["coordinator", "artifacts"] {
        private_dir(&root.join(name))?;
    }
    let ssh = SshTarget::new(&profile.ssh_program, &profile.ssh_host)
        .with_command_timeout(Duration::from_secs(60));
    let transport = Arc::new(RecordingTransport {
        inner: SlurmTaskTransport::new(SlurmSettings {
            apptainer: None,
            ssh: ssh.clone(),
            scratch_dir: profile.remote_scratch_root.clone(),
            local_artifact_root: root.join("artifacts"),
            partition: profile.partition.clone(),
            account: Some(profile.account.clone()),
            gpus: None,
            qos: None,
            mem_per_cpu: "1G".into(),
            default_time: "00:02:00".into(),
            poll_interval: Duration::from_secs(2),
        }),
        root: root.clone(),
    });
    let store = Arc::new(RetainedOnlyStore {
        inner: SshArtifactStore::new(
            ssh.clone(),
            &profile.remote_scratch_root,
            root.join("artifacts"),
        )
        .with_data_home(data_home(profile, fixture))?,
        upload_attempts: AtomicUsize::new(0),
        arrow_download_attempts: AtomicUsize::new(0),
    });
    let executor = TypedRemoteTaskExecutor::new(
        Arc::new(RemoteTaskExecutor::new(
            transport,
            store.clone(),
            root.join("coordinator"),
        )),
        profile.worker.clone(),
    )?;
    let result = executor.run(execution).await;
    private_json(
        &root.join("RESULT.json"),
        &match &result {
            JobResult::Success { id, .. } => json!({"status":"success","task_id":id}),
            JobResult::Failed { id, error, .. } => {
                json!({"status":"failed","task_id":id,"error":error.to_string()})
            }
        },
    )?;
    // Missing lease/receipt is an error, never an expected permission denial.
    let lease: TaskLease = serde_json::from_slice(&std::fs::read(root.join("LEASE.json"))?)?;
    let receipt: TaskAttemptReceipt =
        serde_json::from_slice(&std::fs::read(root.join("REMOTE_RECEIPT.json"))?)?;
    if label == "denied-read" {
        denied_stop(&ssh, &root, &lease, &receipt).await?;
    } else {
        stopped_proof(&ssh, &root, &lease).await?;
    }
    private_json(
        &root.join("TRANSFER_COUNTS.json"),
        &json!({"upload_attempts":store.upload_attempts.load(Ordering::SeqCst),"arrow_download_attempts":store.arrow_download_attempts.load(Ordering::SeqCst)}),
    )?;
    if store.upload_attempts.load(Ordering::SeqCst) != 0
        || store.arrow_download_attempts.load(Ordering::SeqCst) != 0
    {
        return Err("warehouse used forbidden coordinator payload transfer".into());
    }
    if !Path::new(&receipt.workspace).starts_with(&profile.remote_scratch_root)
        || receipt.task_manifest.path != format!("{}/task.json", receipt.workspace)
    {
        return Err("warehouse receipt escaped the admitted task namespace".into());
    }
    // Failed tasks do not go through RemoteTaskExecutor's success download.
    // Read back every actual durable manifest explicitly after its stop proof.
    let manifest = store
        .inner
        .download(receipt.task_manifest.clone(), label, "verified-task.json")
        .await?;
    let dispatch: TaskDispatch = serde_json::from_slice(&std::fs::read(&manifest.path)?)?;
    private_json(&root.join("DURABLE_DISPATCH.json"), &dispatch)?;
    let envelope = &dispatch.spec.spec["typed_dispatch"];
    if receipt.executor != "slurm"
        || receipt.task_id != label
        || lease.task_id != label
        || envelope["worker"] != serde_json::to_value(&profile.worker)?
        || envelope["original_vfs_principal"]
            != serde_json::to_value(VfsPrincipal::new(12345, 12345))?
        || !Path::new(&receipt.workspace).starts_with(&profile.remote_scratch_root)
    {
        return Err("warehouse real attempt identity/principal mismatch".into());
    }
    Ok((result, receipt, lease))
}

// Unlike the original successful-smoke helper this verifies a deliberately
// failed task. Terminal scheduler observations remain separate from software
// outcome; nothing accepts timeout/cancellation or missing allocation rows.
pub(super) async fn denied_stop(
    ssh: &SshTarget,
    root: &Path,
    lease: &TaskLease,
    receipt: &TaskAttemptReceipt,
) -> SmokeResult<()> {
    let job = &lease.lease_id;
    if job.is_empty() || !job.bytes().all(|b| b.is_ascii_digit()) {
        return Err("invalid denied job id".into());
    }
    let queue = capture(
        ssh,
        &format!("LC_ALL=C squeue -h -j {job} -o %T"),
        &root.join("SQUEUE.json"),
    )
    .await?;
    let accounting = capture(
        ssh,
        &format!("sacct -n -P -j {job} --format=JobIDRaw,State,ExitCode,End"),
        &root.join("SACCT.json"),
    )
    .await?;
    let control = capture(
        ssh,
        &format!("scontrol show job {job}"),
        &root.join("SCONTROL.json"),
    )
    .await?;
    let mut valid = queue["queue_absent"] == true
        && accounting["exit_code"] == 0
        && control["exit_code"] == 0
        && receipt.status == "failed"
        && receipt.exit_code != 0
        && receipt.output_artifacts.is_empty()
        && receipt.output_artifacts_by_port.is_empty();
    let mut allocations = 0;
    let mut expected_state = None;
    let mut expected_exit = None;
    let mut seen = std::collections::BTreeSet::new();
    for line in accounting["stdout"]
        .as_str()
        .unwrap_or("")
        .lines()
        .filter(|s| !s.trim().is_empty())
    {
        let fields = line
            .trim()
            .trim_end_matches('|')
            .split('|')
            .collect::<Vec<_>>();
        if fields.len() != 4 {
            valid = false;
            continue;
        }
        valid &= seen.insert(fields[0].to_owned())
            && (fields[0] == job || fields[0].starts_with(&format!("{job}.")))
            && !fields[3].is_empty()
            && !["Unknown", "None", "N/A"].contains(&fields[3]);
        valid &= (fields[1] == "COMPLETED" && fields[2] == "0:0")
            || (fields[1] == "FAILED"
                && fields[2].split_once(':').is_some_and(|(code, signal)| {
                    code.parse::<u32>().is_ok_and(|n| n > 0) && signal == "0"
                }));
        if fields[0] == job {
            allocations += 1;
            expected_state = Some(fields[1].to_owned());
            expected_exit = Some(fields[2].to_owned());
            valid &= fields[1] == "FAILED" && fields[2] == format!("{}:0", receipt.exit_code);
        }
    }
    let fields = control["stdout"]
        .as_str()
        .unwrap_or("")
        .split_whitespace()
        .collect::<Vec<_>>();
    valid &= allocations == 1
        && fields.contains(&format!("JobId={job}").as_str())
        && fields.contains(
            &format!(
                "JobState={}",
                expected_state.as_deref().unwrap_or("MISSING")
            )
            .as_str(),
        )
        && fields.contains(
            &format!("ExitCode={}", expected_exit.as_deref().unwrap_or("MISSING")).as_str(),
        );
    private_json(
        &root.join("STOP_PROOF.json"),
        &json!({"verified":valid,"job_id":job,"basis":["SQUEUE.json","SACCT.json","SCONTROL.json"],"expected_task_failure":true,"software_success_inferred":false,"remote_scratch_retained":true}),
    )?;
    if !valid {
        return Err("denied task lacks exact independent failed-terminal proof".into());
    }
    Ok(())
}

fn successful_frame(
    result: JobResult,
    receipt: &TaskAttemptReceipt,
) -> SmokeResult<datafusion::prelude::DataFrame> {
    if receipt.status != "success" || receipt.exit_code != 0 {
        return Err("warehouse task receipt failed".into());
    }
    let JobResult::Success { outputs, .. } = result else {
        return Err("warehouse coordinator execution failed".into());
    };
    let Some(NodeValue::DataFrame(frame)) = outputs.get(&0) else {
        return Err("warehouse did not return retained DataFrame".into());
    };
    Ok(frame.clone())
}

async fn local_reject(frame: &datafusion::prelude::DataFrame, root: &Path) -> SmokeResult<()> {
    let collect = frame
        .clone()
        .collect()
        .await
        .err()
        .ok_or("retained rows were collected locally")?
        .to_string();
    let count = frame
        .clone()
        .count()
        .await
        .err()
        .ok_or("retained count executed locally")?
        .to_string();
    if !collect.contains("remote") || !count.contains("remote") {
        return Err("local failures were not retained remote-placement rejection".into());
    }
    private_json(
        &root.join("LOCAL_ROW_REJECTION.json"),
        &json!({"collect_error":collect,"count_error":count,"schema":format!("{:?}",frame.schema())}),
    )?;
    Ok(())
}

pub(super) async fn run() -> SmokeResult<()> {
    let mut profile = read_profile_mode(true)?;
    let fixture = Path::new(&profile.remote_scratch_root)
        .parent()
        .and_then(Path::to_str)
        .ok_or("warehouse runs parent required")?
        .to_owned();
    if Path::new(&profile.remote_scratch_root)
        .file_name()
        .and_then(|s| s.to_str())
        != Some("runs")
        || !clean_absolute(Path::new(&fixture))
    {
        return Err("warehouse scratch must be unique fixture_root/runs".into());
    }
    let base_worker = profile.worker.clone();
    let worker_policy = policy(&fixture, None);
    let hash = format!("{:x}", Sha256::digest(worker_policy.as_bytes()));
    profile.worker.worker_vfs_manifest = Some(Path::new(&fixture).join("worker-vfs.toml"));
    profile.worker.worker_vfs_sha256 = Some(hash.clone());
    let principal = VfsPrincipal::new(12345, 12345);
    private_json(
        &profile.local_root.join("WAREHOUSE_START.json"),
        &json!({"source_revision":dag_core::source_revision(),"test_executable_sha256":digest(&std::env::current_exe()?)?,"base_worker":base_worker,"effective_worker":profile.worker,"fixture_root":fixture,"remote_scratch_root":profile.remote_scratch_root,"worker_vfs_manifest_sha256":hash,"principal":principal,"science":false,"coordinator_factory_tested":false,"worker_factory":"production core/file_to_dataframe"}),
    )?;
    provision(&profile, &fixture, &worker_policy).await?;
    let ctx = context(&profile, &fixture, principal)
        .map_err(|e| format!("warehouse coordinator context: {e}"))?;
    // Readiness identity before any sbatch, independently of worker launch pins.
    let ssh = SshTarget::new(&profile.ssh_program, &profile.ssh_host)
        .with_command_timeout(Duration::from_secs(60));
    let identity = capture(
        &ssh,
        &format!(
            "{} task-worker --identity",
            quote(&profile.worker.executable.to_string_lossy())
        ),
        &profile.local_root.join("WORKER_IDENTITY.json"),
    )
    .await?;
    let actual: Value = serde_json::from_str(
        identity["stdout"]
            .as_str()
            .ok_or("worker identity missing")?,
    )?;
    if identity["exit_code"] != 0
        || actual["source_revision"] != profile.worker.expected_source_revision
        || actual["executable_sha256"] != profile.worker.executable_sha256
    {
        return Err("warehouse worker pin differs from actual ELF".into());
    }
    let (public, public_receipt, public_lease) = execute(
        &profile,
        &fixture,
        "public-read",
        read_task(
            "public-read",
            "vfs:///warehouse-public/values.csv",
            ctx.clone(),
        ),
    )
    .await?;
    let frame = successful_frame(public, &public_receipt)?;
    local_reject(&frame, &profile.local_root.join("public-read")).await?;
    let (denied, denied_receipt, denied_lease) = execute(
        &profile,
        &fixture,
        "denied-read",
        read_task(
            "denied-read",
            "vfs:///warehouse-private/values.csv",
            ctx.clone(),
        ),
    )
    .await?;
    if !matches!(denied, JobResult::Failed { .. }) {
        return Err("private worker reader unexpectedly succeeded".into());
    }
    let settings = profile.warehouse.as_ref().unwrap();
    let err_path = format!(
        "{}/slurm-{}.err",
        denied_receipt.workspace, denied_lease.lease_id
    );
    let code = format!(
        "import os,json,stat\np={}\nf=os.open(p,os.O_RDONLY|os.O_NONBLOCK|os.O_NOFOLLOW)\ns=os.fstat(f);assert stat.S_ISREG(s.st_mode) and s.st_size<=1048576\nb=os.read(f,1048577);os.close(f)\nprint(json.dumps({{'stderr':b.decode('utf8','replace')}}))",
        json!(err_path)
    );
    let denial = python(
        &ssh,
        &settings.remote_python,
        &code,
        &profile.local_root.join("denied-read/WORKER_ERROR.json"),
    )
    .await?;
    let error = denial["stderr"].as_str().unwrap_or("").to_ascii_lowercase();
    if !(error.contains("permission") || error.contains("denied"))
        || !error.contains("warehouse-private")
    {
        return Err(
            "negative task failed for a reason other than the intended VFS permission denial"
                .into(),
        );
    }
    let execution = TaskExecution {
        node: Box::new(dag_core::dag::GatherNode::default()),
        submission: TaskSubmission {
            spec: TaskSpec {
                id: "retained-followup".into(),
                kind: "logical_gather".into(),
                spec: json!({}),
                logical_node: None,
                item_key: None,
                item: None,
                inputs: vec![TaskInputBinding {
                    name: "retained".into(),
                    port: 0,
                    source: TaskInputSource::UpstreamPort {
                        from: "public-read".into(),
                        from_port: 0,
                    },
                    payload: "dataframe".into(),
                    path: None,
                    fingerprint: None,
                    staged_paths: vec![],
                }],
                outputs: vec![TaskOutputBinding {
                    name: "table".into(),
                    port: 0,
                    payload: "any".into(),
                    artifact_paths: vec![],
                }],
            },
            inputs: vec![NodeInput {
                port: 0,
                data: NodeValue::DataFrame(frame),
            }],
            resources: resources(),
        },
        engine_ctx: ctx,
        reporter: NodeReporter::noop(),
        cancellation: CancellationToken::new(),
    };
    let (followup, followup_receipt, followup_lease) =
        execute(&profile, &fixture, "retained-followup", execution).await?;
    let final_frame = successful_frame(followup, &followup_receipt)?;
    local_reject(&final_frame, &profile.local_root.join("retained-followup")).await?;
    let source = public_receipt
        .output_artifacts_by_port
        .get(&0)
        .filter(|f| f.len() == 1)
        .and_then(|f| f.first())
        .ok_or("missing single public Arrow")?;
    let dispatch: TaskDispatch = serde_json::from_slice(&std::fs::read(
        profile
            .local_root
            .join("retained-followup/DURABLE_DISPATCH.json"),
    )?)?;
    let forwarded: BTreeMap<String, Vec<FileRef>> =
        serde_json::from_value(dispatch.spec.spec["_autonomics_input_artifacts"].clone())?;
    let refs = forwarded
        .get("retained")
        .ok_or("missing forwarded retained artifact")?;
    if refs.len() != 1
        || refs[0].path != source.path
        || artifact_hash(&refs[0])? != artifact_hash(source)?
    {
        return Err("followup did not preserve exact original remote Arrow path/hash".into());
    }
    let local_ipc = local_arrow_paths(&profile.local_root)?;
    private_json(
        &profile.local_root.join("LOCAL_STAGING_INVENTORY.json"),
        &json!({"arrow_files_before_bounded_evidence_download":local_ipc}),
    )?;
    if !local_ipc.is_empty() {
        return Err("warehouse serialized an Arrow payload on the coordinator".into());
    }
    // Bounded independent evidence download, after execution and all stop
    // proofs. It does not collect the coordinator's retained DataFrame.
    let output = followup_receipt
        .output_artifacts_by_port
        .get(&0)
        .filter(|f| f.len() == 1)
        .and_then(|f| f.first())
        .ok_or("missing single followup Arrow")?;
    if output.fingerprint.as_ref().is_none_or(|f| f.size > 65536) {
        return Err("warehouse evidence Arrow exceeds synthetic 64KiB bound".into());
    }
    let bounded_root = profile.local_root.join("bounded-evidence");
    private_dir(&bounded_root)?;
    let evidence = SshArtifactStore::new(ssh, &profile.remote_scratch_root, bounded_root);
    let file = evidence
        .download(output.clone(), "warehouse-verification", "six-values")
        .await?;
    let schema = Schema::new(vec![
        Field::new("id", DataType::Int64, true),
        Field::new("label", DataType::Utf8, true),
    ]);
    let expected = vec![(1, "alpha".into()), (2, "beta".into()), (3, "gamma".into())];
    if digest(Path::new(&file.path))? != artifact_hash(output)?
        || arrow_rows(Path::new(&file.path), &schema)? != expected
    {
        return Err("independent warehouse Arrow bytes/schema/rows differ".into());
    }
    private_json(
        &profile.local_root.join("WAREHOUSE_PASS.json"),
        &json!({"technical_smoke":"passed","source_revision":dag_core::source_revision(),"worker_executable_sha256":profile.worker.executable_sha256,"jobs":{"public-read":public_lease.lease_id,"denied-read":denied_lease.lease_id,"retained-followup":followup_lease.lease_id},"expected_rows":expected,"output_sha256":artifact_hash(output)?,"coordinator_factory_tested":false,"worker_factory":"production core/file_to_dataframe","remote_scratch_retained":true,"scientific_acceptance":false}),
    )?;
    Ok(())
}

fn local_arrow_paths(root: &Path) -> SmokeResult<Vec<PathBuf>> {
    let mut result = vec![];
    for entry in std::fs::read_dir(root)? {
        let path = entry?.path();
        let metadata = std::fs::symlink_metadata(&path)?;
        if metadata.file_type().is_symlink() {
            return Err("unexpected symlink in private warehouse evidence".into());
        }
        if metadata.is_dir() {
            result.extend(local_arrow_paths(&path)?);
        } else if path.extension().is_some_and(|s| s == "arrow") {
            result.push(path);
        }
    }
    Ok(result)
}

#[test]
fn synthetic_policy_roundtrips_and_keeps_private_mount_denied() {
    let local = vfs::VfsManifest::from_toml(&policy("/synthetic-warehouse", None)).unwrap();
    assert!(local.mount.iter().all(|m| m.read_only));
    assert_eq!(local.mount.len(), 3);
    let remote = vfs::VfsManifest::from_toml(&policy(
        "/synthetic-warehouse",
        Some(("toy-ssh", "/usr/bin/python3")),
    ))
    .unwrap();
    let mounts = Arc::new(vfs::MountedObjectStore::from_manifest(&remote).unwrap());
    let fixture = tempfile::tempdir().unwrap();
    let storage = vfs::OpendalFileStorage::with_mounts(fixture.path(), mounts)
        .with_principal(VfsPrincipal::new(12345, 12345));
    assert!(
        storage
            .check_readable("/warehouse-public/values.csv")
            .is_ok()
    );
    assert!(
        storage
            .check_readable("/warehouse-private/values.csv")
            .is_err()
    );
    assert!(
        storage
            .check_readable("/warehouse-account/private/values.csv")
            .is_err()
    );
}
