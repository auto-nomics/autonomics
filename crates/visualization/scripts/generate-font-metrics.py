#!/usr/bin/env python3
"""Generate font advances and legacy kerning from the exact shipped WOFF2.
Development-only dependency: fonttools[woff]. No runtime font parser is needed.
"""
from pathlib import Path
import hashlib
from fontTools.ttLib import TTFont
root = Path(__file__).resolve().parents[3]
font_path = root / "apps/gui/public/excalidraw/fonts/Liberation/LiberationSans-Regular.woff2"
font = TTFont(font_path)
cmap = font.getBestCmap()
reverse = {}
for codepoint, glyph in cmap.items():
    reverse.setdefault(glyph, []).append(codepoint)
pairs = {}
for subtable in font["kern"].kernTables:
    if subtable.coverage & 1 and not subtable.coverage & 6:
        for (left, right), value in subtable.kernTable.items():
            for a in reverse.get(left, []):
                for b in reverse.get(right, []):
                    pairs[(a, b)] = pairs.get((a, b), 0) + value
checksum = hashlib.sha256(font_path.read_bytes()).hexdigest()
lines = ["// Generated by scripts/generate-font-metrics.py; do not edit.",
         "// Liberation Sans, SIL OFL-1.1; license and font ship in GUI public/excalidraw/fonts/Liberation/.",
         f'pub const SHA256: &str = "{checksum}";',
         f"pub const UNITS_PER_EM: f64 = {font['head'].unitsPerEm}.0;",
         "pub const ADVANCES: &[(u32, u16)] = &["]
lines += [f"    ({cp}, {font['hmtx'].metrics[glyph][0]})," for cp, glyph in sorted(cmap.items())]
lines += ["];", "pub const KERNING: &[(u32, u32, i16)] = &["]
lines += [f"    ({a}, {b}, {v})," for (a, b), v in sorted(pairs.items()) if v]
lines += ["];", ""]
(root / "crates/visualization/src/font_metrics.rs").write_text("\n".join(lines))
print(f"Generated {len(cmap)} advances and {len(pairs)} kerning pairs; SHA256={checksum}")
