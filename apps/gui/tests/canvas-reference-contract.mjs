import assert from 'node:assert/strict';
import {checkReferenceScene} from './helpers/canvas-live-reference.mjs';
const source={id:'reference',type:'image',x:0,y:0,width:840,height:180,fileId:'r'};
const original={elements:[source],files:{r:{dataURL:'data:image/png;base64,fixture'}}};
const shape=(id,x)=>({id,type:'rectangle',x,y:240,width:180,height:80,opacity:100,boundElements:[{id:`${id}-text`,type:'text'},...(['a','b'].filter(a=>a==='a'?id!=='review':id!=='collect').map(id=>({id,type:'arrow'})))]});
const text=(id,label,x)=>({id:`${id}-text`,type:'text',containerId:id,text:label,originalText:label,x,y:260,width:100,height:25,fontSize:20,opacity:100});
const arrow=(id,from,to,x)=>({id,type:'arrow',x,y:280,width:60,height:0,opacity:100,startBinding:{elementId:from},endBinding:{elementId:to},startArrowhead:null,endArrowhead:'arrow'});
const candidate={elements:[structuredClone(source),shape('collect',0),text('collect','Collect',20),shape('image',240),text('image','Image',260),shape('review',480),text('review','Review',500),arrow('a','collect','image',180),arrow('b','image','review',420)],files:structuredClone(original.files)};
checkReferenceScene(original,candidate);
const reject=mutate=>{const altered=structuredClone(candidate);mutate(altered);assert.throws(()=>checkReferenceScene(original,altered));};
reject(d=>d.elements[0].x=1);
reject(d=>d.elements.push(structuredClone(source)));
reject(d=>d.appState={viewBackgroundColor:'#000000'});
reject(d=>d.files.r.dataURL='another image');
reject(d=>d.elements.find(e=>e.id==='collect-text').containerId=null);
reject(d=>d.elements.find(e=>e.id==='review-text').text='Inspect');
reject(d=>d.elements.find(e=>e.id==='a').endBinding.elementId='review');
reject(d=>d.elements.find(e=>e.id==='b').endArrowhead=null);
reject(d=>d.elements.find(e=>e.id==='collect').boundElements=[]);
reject(d=>d.elements.find(e=>e.id==='collect').y=100);
reject(d=>d.elements.find(e=>e.id==='collect-text').opacity=0);
reject(d=>d.elements.push({id:'raster-copy',type:'image',x:0,y:0,width:100,height:100,opacity:100}));
console.log('reference reconstruction: source bytes/identity, complete visible text, native reciprocal bindings, direction and separate editable objects verified');
