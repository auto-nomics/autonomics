import assert from 'node:assert/strict';
import {notificationLookup} from '../src/features/discovery/subscription-model.ts';
const record=(source,identifiers)=>({source,article:{id:'fixture',title:'Same tempting title',identifiers}});
const id=(kind,value)=>({kind,value});
const doi=notificationLookup(record('crossref',[id('doi','https://doi.org/10.1000/Case?x#fragment')]));
assert.equal(doi.request.query,'10.1000/case?x#fragment');
assert.ok(doi.accepts({identifiers:[id('doi','DOI:10.1000/CASE?x#fragment')]}));
assert.ok(!doi.accepts({identifiers:[id('doi','10.1000/case')]}));
assert.ok(!doi.accepts({id:'fixture',title:'Same tempting title',identifiers:[]}));
const pmid=notificationLookup(record('pubmed',[id('pmid','https://pubmed.ncbi.nlm.nih.gov/000123/?x=1')]));
assert.equal(pmid.request.native.parameters.term,'"123"[PMID]');
assert.ok(pmid.accepts({identifiers:[id('pmid','PMID:123')]}));
const arxiv=notificationLookup(record('arxiv',[id('arxiv','https://arxiv.org/pdf/2401.12345v2.pdf')]));
assert.equal(arxiv.request.native.parameters.id_list,'2401.12345v2');
assert.ok(arxiv.accepts({identifiers:[id('arxiv','arXiv:2401.12345v2')]}));
assert.ok(!arxiv.accepts({identifiers:[id('arxiv','2401.12345')]}));
assert.ok(!arxiv.accepts({identifiers:[id('arxiv','2401.12345v3')]}));
assert.equal(notificationLookup(record('arxiv',[id('doi','10.1000/formal-paper')])),null);
assert.equal(notificationLookup(record('crossref',[id('doi','10.1000/a'),id('doi','10.1000/b')])),null);
assert.equal(notificationLookup(record('crossref',[id('doi','10.1000/bad space')])),null);
const oa=notificationLookup(record('openalex',[id('openalex','https://openalex.org/W123456')]));
assert.equal(oa.request.native.parameters.filter,'openalex:W123456');
assert.ok(oa.accepts({identifiers:[id('openalex','W123456')]}));
assert.ok(!oa.accepts({identifiers:[id('openalex','W999999')]}));
const s2=notificationLookup(record('semantic_scholar',[id('s2','A'.repeat(40))]));
assert.equal(s2.request.native.parameters.paper_id,'a'.repeat(40));
assert.equal(notificationLookup(record('openalex',[])),null);
console.log(JSON.stringify({passed:true,scope:'notification strong identities; literal DOI suffixes; PMID wrappers; source IDs; exact arXiv versions; no title fallback'}));
