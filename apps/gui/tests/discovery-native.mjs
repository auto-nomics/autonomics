import '/src/app.css';
import { mountBibliography } from './bibliography-menu-mount.tsx';
import { invoke } from '@tauri-apps/api/core';
const evidence = [];
const wait = async (test, label) => { const deadline = Date.now() + 12000; while (Date.now() < deadline) { const value = test(); if (value) return value; await new Promise(resolve => setTimeout(resolve, 30)); } throw new Error('Timed out: ' + label); };
const visible = node => Boolean(node.getClientRects().length);
const button = text => [...document.querySelectorAll('button')].find(node => visible(node) && (node.textContent.trim() === text || node.getAttribute('aria-label') === text));
const setInput = (input, value) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, value); input.dispatchEvent(new Event('input', { bubbles: true })); };
const api = async (method, path, body = null) => (await invoke('api', { method, path, body, requestId: null })).data;
const finish = async result => { await invoke('smoke_done', { result }); };
window.addEventListener('error', event => void finish({ ok: false, error: event.message, evidence }));
window.addEventListener('unhandledrejection', event => void finish({ ok: false, error: String(event.reason), evidence }));
try {
  mountBibliography(document.body);
  (await wait(() => button('Discover'), 'workspace tab')).click();
  const input = await wait(() => document.querySelector('[aria-label="Discover literature"]'), 'query');
  setInput(input, 'gene');
  (await wait(() => button('Search sources'), 'submit')).click();
  (await wait(() => button('Native discovery paper'), 'first source batch')).click();
  const checkbox = await wait(() => document.querySelector('input[aria-label="Select Native discovery paper"]'), 'selection'); checkbox.click();
  evidence.push('actual native IPC create, events and first-source delivery');
  (await wait(() => button('Show updated results'), 'slow source update')).click();
  const version = await wait(() => { const node = document.querySelector('[aria-label="Candidate source version"]'); return node?.options.length === 2 ? node : null; }, 'both metadata variants');
  version.value = '1'; version.dispatchEvent(new Event('change', { bubbles: true }));
  (await wait(() => button('Preview import'), 'preview')).click();
  (await wait(() => { const node = button('Confirm import'); return node && !node.disabled ? node : null; }, 'confirm')).click();
  await wait(() => document.body.textContent.includes('1 imported · 0 already present · 0 failed'), 'successful import');
  await wait(() => document.body.textContent.includes('Already in target library'), 'updated library presence');
  evidence.push('source-version selection, preview and transactional import');
  evidence.push('target library presence after import');
  const articles = (await api('GET', '/bib/articles')).articles;
  const imported = articles.find(article => article.title === 'Native discovery selected variant');
  if (!imported) throw new Error('Selected source variant was not persisted');
  const snapshot = await api('GET', '/bib/articles/' + encodeURIComponent(imported.id) + '/discovery-provenance');
  const sessionId = snapshot.entries[0].provenance.session_id;
  await api('DELETE', '/bib/search/sessions/' + sessionId);
  (await wait(() => button('Library'), 'return to library')).click();
  (await wait(() => [...document.querySelectorAll('[data-bib-row-primary]')].find(node => visible(node) && node.textContent.includes(imported.title)), 'import visible in library')).click();
  const summary = await wait(() => [...document.querySelectorAll('summary')].find(node => visible(node) && node.textContent.includes('Discovery provenance')), 'durable provenance control'); summary.click();
  await wait(() => document.body.textContent.includes('openalex · imported'), 'durable source history');
  const details = [...document.querySelectorAll('summary')].find(node => visible(node) && node.textContent.includes('Original query and source execution')); details.click();
  await wait(() => document.body.textContent.includes('native fixture translation'), 'executed query provenance');
  if (snapshot.total !== 1 || snapshot.entries[0].provenance.selected.source !== 'openalex') throw new Error('Provenance mismatch');
  evidence.push('library change notification, session deletion and durable provenance GUI');
  (await wait(() => button('Discover'), 'return to discovery')).click();
  if (input.value !== 'gene') throw new Error('Workspace switching lost the discovery query');
  const native = [...document.querySelectorAll('label')].find(node => node.textContent.trim() === 'Native query')?.querySelector('input');
  if (!native) throw new Error('Native query mode control missing'); native.click();
  const sourceRadio = name => [...document.querySelectorAll('input[type="radio"]')].find(node => node.closest('label')?.textContent.trim() === name);
  (await wait(() => sourceRadio('arxiv'), 'arxiv radio')).click();
  const parameters = await wait(() => document.querySelector('textarea[aria-label="Native source parameters"]'), 'native source parameters');
  const arxivQuery = 'ti:gene ANDNOT au:Smith';
  Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(parameters, JSON.stringify({search_query: arxivQuery}));
  parameters.dispatchEvent(new Event('input', {bubbles:true}));
  (await wait(() => button('Search sources'), 'native search action')).click();
  await wait(() => button('Native arxiv HTTP gene paper'), 'native arxiv SDK HTTP source result');
  const queryDetails = [...document.querySelectorAll('summary')].find(node => visible(node) && node.textContent.trim() === 'Query details');
  if (!queryDetails) throw new Error('Native arxiv query details missing'); queryDetails.click();
  await wait(() => document.body.textContent.includes(arxivQuery), 'unmodified arxiv query parameters');
  sourceRadio('pubmed').click();
  await wait(() => JSON.parse(parameters.value).term === 'gene', 'separate pubmed draft');
  sourceRadio('arxiv').click();
  await wait(() => JSON.parse(parameters.value).search_query === arxivQuery, 'arxiv draft restored');
  evidence.push('actual native arxiv SDK HTTP/Atom query and per-source draft preservation');
  sourceRadio('crossref').click();
  await wait(() => JSON.parse(parameters.value)['query.bibliographic'] === 'gene', 'Crossref bibliographic draft');
  Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(parameters, JSON.stringify({'query.bibliographic':'gene editing',filter:'type:journal-article'}));
  parameters.dispatchEvent(new Event('input', {bubbles:true}));
  (await wait(() => button('Search sources'), 'Crossref native search action')).click();
  await wait(() => button('Native crossref HTTP gene paper'), 'native Crossref SDK HTTP source result');
  await wait(() => document.body.textContent.includes('Crossref text fields are fuzzy relevance hints'), 'Crossref source matching notice');
  (await wait(() => button('Fetch next page'), 'Crossref continuation action')).click();
  (await wait(() => button('Show updated results'), 'Crossref next page event')).click();
  await wait(() => document.body.textContent.includes('26 obtained candidates'), 'Crossref next page candidate count');
  const resultList = document.querySelector('[aria-label="Discovery result list"]');
  await wait(() => resultList.querySelector('[data-loaded-count="26"]'), 'Crossref refreshed result rows');
  resultList.scrollTop = resultList.scrollHeight; resultList.dispatchEvent(new Event('scroll'));
  await wait(() => button('Native crossref next HTTP gene paper'), 'Crossref next page visible in virtual list');
  if (button('Fetch next page')) throw new Error('Crossref short terminal page still offers continuation');
  sourceRadio('arxiv').click();
  await wait(() => JSON.parse(parameters.value).search_query === arxivQuery, 'arxiv draft preserved across Crossref');
  sourceRadio('crossref').click();
  await wait(() => JSON.parse(parameters.value)['query.bibliographic'] === 'gene editing', 'Crossref draft restored');
  evidence.push('actual native Crossref SDK HTTP metadata query, matching notice, cursor continuation, virtual results and source draft preservation');
  sourceRadio('semantic_scholar').click();
  await wait(() => JSON.parse(parameters.value).query === 'gene', 'S2 native query draft');
  Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(parameters,JSON.stringify({endpoint:'bulk',query:'(gene | asthma) -mice',year:'2020-2024'}));
  parameters.dispatchEvent(new Event('input',{bubbles:true}));
  (await wait(() => button('Search sources'),'S2 search action')).click();
  await wait(() => button('Native S2 HTTP gene paper'),'actual S2 SDK HTTP source result');
  await wait(() => document.body.textContent.includes('Bulk retrieval preserves supported Boolean constraints'),'bulk source ordering notice');
  (await wait(() => button('Fetch next page'),'S2 buffered continuation')).click();
  (await wait(() => button('Show updated results'),'S2 buffered page event')).click();
  await wait(() => resultList.querySelector('[data-loaded-count="30"]'),'S2 refreshed result rows');
  resultList.scrollTop=resultList.scrollHeight;resultList.dispatchEvent(new Event('scroll'));
  await wait(() => button('Native S2 buffered last paper'),'S2 last buffered result visible');
  if(button('Fetch next page')) throw new Error('S2 terminal batch still offers continuation');
  sourceRadio('crossref').click();
  await wait(() => JSON.parse(parameters.value)['query.bibliographic']==='gene editing','Crossref draft retained across S2');
  sourceRadio('semantic_scholar').click();
  await wait(() => JSON.parse(parameters.value).query==='(gene | asthma) -mice','S2 native draft restored');
  evidence.push('actual native S2 SDK HTTP Boolean query with year filter; 25+5 buffered results after the upstream fixture closed; virtual last row and source drafts');
  await finish({ ok: true, runtime: 'Tauri WebKitGTK', evidence });
} catch (error) {
  const list = document.querySelector('[aria-label="Discovery result list"]');
  await finish({ ok: false, error: String(error), evidence, result_list: list && { loaded: list.querySelector('[data-loaded-count]')?.getAttribute('data-loaded-count'), scroll_top: list.scrollTop, scroll_height: list.scrollHeight, client_height: list.clientHeight, mounted_titles: [...list.querySelectorAll('[data-bib-row-primary]')].map(node => node.textContent) } });
}
