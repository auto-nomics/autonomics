import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {planLabelReview,planLabelFeedback} from '../src/features/canvas/canvas-plan-review.ts';
const source={version:2,document:{nodes:[{id:'receptor',label:'IFNGR1:JAK1:IFNGR2:JAK2'}],edges:[]}};
const scene={elements:[{id:'anchor',customData:{scientificId:'receptor',planningSource:source}},{id:'label',type:'text',containerId:'anchor',text:'IFNGR1:JAK1:\nIFNGR2:JAK2'}]};
assert.equal(planLabelReview(scene).items[0].status,'same');
scene.elements[1].originalText=source.document.nodes[0].label;
scene.elements[1].text='shortened receptor';
assert.equal(planLabelReview(scene).items[0].status,'changed','complete originalText must not hide shortened visible text');
assert.equal(planLabelReview(scene).items[0].original,source.document.nodes[0].label);
scene.elements[1].text=source.document.nodes[0].label;
scene.elements.push({id:'same-snapshot',customData:{planningSource:{document:source.document,version:2}}});
assert.equal(planLabelReview(scene).available,true,'JSON property order does not create a source conflict');
scene.elements.pop();
scene.elements[1].originalText='IFNGR receptor';
scene.elements[1].text='IFNGR receptor';
assert.equal(planLabelReview(scene).items[0].status,'changed');
scene.elements[0].customData.visualLabelIds=['label'];delete scene.elements[1].containerId;
assert.equal(planLabelReview(scene).items[0].actual,'IFNGR receptor');
scene.elements.push({...scene.elements[1],id:'duplicate',containerId:'anchor'});
assert.equal(planLabelReview(scene).items[0].status,'ambiguous');
scene.elements.pop();scene.elements[1].isDeleted=true;
assert.equal(planLabelReview(scene).items[0].status,'missing');
assert.equal(planLabelReview({elements:[]}).available,false);
scene.elements.push({id:'other',customData:{planningSource:{...source,version:3}}});
assert.equal(planLabelReview(scene).available,false);
const relation={elements:[{id:'a',customData:{scientificId:'a',planningSource:{version:1,document:{nodes:[{id:'a',label:'A'},{id:'b',label:'B'}],edges:[{from:'a',to:'b',label:'activates'}]}}}},{id:'b',customData:{scientificId:'b'}},{id:'arrow',type:'arrow',startBinding:{elementId:'a'},endBinding:{elementId:'b'}},{id:'edge-text',type:'text',containerId:'arrow',originalText:'activates'}]};
assert.equal(planLabelReview(relation).items.at(-1).status,'same');
relation.elements.push({...relation.elements[2],id:'parallel'});
assert.equal(planLabelReview(relation).items.at(-1).status,'ambiguous');
const many={elements:[{id:'snapshot',customData:{planningSource:{version:1,document:{nodes:Array.from({length:205},(_,i)=>({id:String(i),label:'x'})),edges:[]}}}}]};
assert.equal(planLabelReview(many).omitted,5);
assert.equal(planLabelFeedback(many).items.length,20);
assert.equal(planLabelFeedback(many).feedback_omitted,180);
many.elements[0].customData.planningSource.document.nodes[0].label='A'.repeat(3000);
assert.equal(planLabelFeedback(many).items[0].expected.length,600);
assert.equal(planLabelFeedback(many).items[0].text_truncated,true);
if(process.env.CANVAS_PLAN_REPLAY){
 const candidates=JSON.parse(readFileSync(process.env.CANVAS_PLAN_REPLAY,'utf8'));
 const root=candidates.find(c=>c.id==='c9df2804-1424-4ba8-8075-917e85fb8718');
 const child=candidates.find(c=>c.id==='b3c30326-487c-4376-9d8b-5fcb9b5a696a');
 assert.ok(root && child);
 const before=planLabelReview(root.document),after=planLabelReview(child.document);
 assert.ok(before.available && after.available);
 assert.equal(before.items.filter(i=>i.status!=='same').length,0);
 assert.ok(after.items.some(i=>i.status==='changed' && i.expected.includes('IFNGR1:JAK1:IFNGR2:JAK2')));
 console.log('actual v13 root unchanged; shortened receptor and relationship labels detected:',after.items.filter(i=>i.status!=='same').map(i=>i.key));
}
const scoped = planLabelFeedback(scene);
assert.equal(scoped.comparison_basis,'embedded_historical_plan_snapshot');
assert.equal(scoped.expected_field_meaning,'historical_snapshot_value_not_a_required_correction');
assert.equal(scoped.scientific_correctness_assessed,false);
assert.equal(scoped.restoration_authorized,false);
assert.ok(scoped.guidance.includes('局部排版任务保留当前内容'));
console.log('plan label review: whitespace, original text, detached ownership, ambiguity, missing labels, snapshot conflicts and bounded scope passed');

// A reviewed label can intentionally differ from the immutable historical plan.
const reviewed={elements:[{id:'node',customData:{scientificId:'reviewed',planningSource:{version:1,document:{nodes:[{id:'reviewed',label:'Old unreviewed residue attribution'}],edges:[]}}}},{id:'text',type:'text',containerId:'node',text:'Reviewed activity label',originalText:'Reviewed activity label'}]};
const beforeReview=JSON.stringify(reviewed),feedback=planLabelFeedback(reviewed);
assert.equal(feedback.differences,1);
assert.equal(feedback.items[0].expected,'Old unreviewed residue attribution');
assert.equal(feedback.items[0].actual,'Reviewed activity label');
assert.equal(feedback.restoration_authorized,false);
assert.equal(feedback.scientific_correctness_assessed,false);
assert.equal(JSON.stringify(reviewed),beforeReview);
