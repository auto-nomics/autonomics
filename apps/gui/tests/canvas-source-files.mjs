import assert from 'node:assert/strict';
import {preserveSourceFiles} from '../src/features/canvas/canvas-source-files.ts';
const saved={old:{id:'old',dataURL:'original-source',mimeType:'image/svg+xml'},retired:{id:'retired',dataURL:'historical-source'}};
const native={elements:[{id:'art',fileId:'old'}],files:{old:{id:'old',dataURL:'normalized-cache'},new:{id:'new',dataURL:'new-user-image'}}};
const result=JSON.parse(preserveSourceFiles(JSON.stringify(native),saved));
assert.deepEqual(result.files.old,saved.old);
assert.deepEqual(result.files.retired,saved.retired);
assert.deepEqual(result.files.new,native.files.new);
assert.deepEqual(result.elements,native.elements);
assert.equal(native.files.old.dataURL,'normalized-cache');
assert.equal(saved.old.dataURL,'original-source');
console.log('canvas-source-files: immutable sources override rendering cache; historical and new files retained');
