export type CaptionStyle = "concise" | "detailed";
export function captionGuidance(style: CaptionStyle) {
  const common = "说明风格只控制图注组织，不授权修改已确认的科学标签、关系或依据。物种/刺激范围、终点和关键不确定性必须在画面中可见，不能只藏在元数据。精简图注时保留检索覆盖范围与不确定性限定：“本次已读来源未见”不能改成“没有”或“不存在”，“可能”不能改成确定结论。完整实际来源 URL 继续保留在节点/关系 evidence 及来源导出中；不得删掉依据来压缩图稿。用户本轮明确要求优先。";
  return style === "detailed"
    ? `${common} 用户选择详细说明：将来源与较长说明放入独立图注区域，使用可读字号和段落；不要通过无限加宽说明或极小字号压缩全部内容。核对图注与核心图形的信息层级。`
    : `${common} 用户选择简洁说明：核心图形应保持视觉主导。图内说明用简短段落写出范围、终点和关键不确定性，避免逐字重复计划或逐条堆砌完整 URL。优先按“范围与终点”“关键限定”组织，每个信息块用一到两句，避免在多个段落重复同一限定。检索次数、逐条读源过程和未纳入的每个旁支不默认写成图内清单；与本图解释直接相关的覆盖限制仍须简短可见，不能因精简将“未读取”变为“不存在”。若一句无法容纳关键限定，应保留必要文字并说明需要更大的图注区域，不强行删减。完整书目可由来源导出核对；若用户明确要求在画面列出完整引用则遵从。说明宽度尽量不超过核心图形，长说明可分段排版，不能靠删分子名或缩小到难读字号来塞入。`;
}

export type LayoutPreference = "auto" | "compact" | "horizontal" | "vertical";
export function layoutGuidance(preference: LayoutPreference) {
  const common = "构图偏好只控制空间组织，保留全部已确认节点、关系、标签、来源和分面原意，不通过删除科学内容或缩小到难读字号来压缩图稿。用户明确的版式要求优先。";
  const guidance: Record<LayoutPreference, string> = {
    auto: "用户选择自动构图：根据节点数量、关系和阅读场景选择布局，先检查长链是否过宽、说明是否可读，再提交候选。",
    compact: "用户选择紧凑分面：避免把长链排成单行横幅。优先用现有 panels 和节点 panel 归属，将相关步骤分段并按多列或多行组织，分面内部优先自动纵向布局以适应长标签；选用网格时也须检查标签换行和行列间距，避免每个分面仍是一条横向长链；跨面板只保留原有显式关系，视觉分段不证明新的生物区室或阶段。保留关系方向，使用可读标签与独立说明区，并检查跨面板连接和标题。新增说明可用 visualization_add_text 的 fit_width:true，在 max_width 内保留完整换行并收紧文字框，避免单行宽框扩大整图边界；已有独立说明框可用 operations 中的 {op:fit_text_width,id}，保留当前换行、字体和可见对齐；它不会处理绑定节点/箭头文字或自动重排其他对象。不要用删字代替收紧框。用户未固定图注位置且本轮允许调整说明布局时，检查短分面下方是否有可读的空白列；可先用 visualization_find_space 核对原生范围与可用宽度。需要列内重排的既有说明用 set_wrapped_text 传完整 originalText、合适 max_width 并保留字号，再从返回候选读取实际高度，按阅读顺序移动到空白列，段落间保留间距；后续操作使用新候选ID/哈希。fit_text_width只收紧现有行，不替代这种重新换行。保留全部范围、限定、许可说明和来源，不为利用空白而缩小字号或压缩科学内容；没有足够空间就保留原排布并说明。",
    horizontal: "用户选择横向流程：优先从左到右组织已有关系，给节点和关系标签留出空间；长链可用明确的视觉分段，不能删改科学内容来强塞一行。",
    vertical: "用户选择纵向流程：优先从上到下组织已有关系，给关系标签和分支留出空间，说明放在独立区域，并检查高度和阅读顺序。",
  };
  return `${common} ${guidance[preference]}`;
}
