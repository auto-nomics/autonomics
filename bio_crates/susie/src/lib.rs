//! `susie` — a pure-Rust port of the **algorithm API** of the R package
//! [`susieR`](https://github.com/stephenslab/susieR) (Wang et al., *JRSSB* 2020),
//! focused exclusively on **GWAS summary-statistics fine-mapping** via
//! [`susie_rss`](crate::susie_rss).
//!
//! ## Scope
//!
//! This crate ports the **standard RSS likelihood** path (`susie_rss` with
//! `lambda = 0`): the Sum of Single Effects (SuSiE) variational model fit via
//! Iterative Bayesian Stepwise Selection (IBSS), using z-scores + an LD
//! correlation matrix R.
//!
//! **In scope:**
//! - `optim`, `EM`, `simple` prior-variance estimation methods
//! - z-score, bhat/shat, and bhat/shat/var_y input paths
//! - PVE adjustment (Wald vs score z-method)
//! - Fixed / estimated residual variance
//! - Prior weights, null weight, non-uniform scaled prior variance
//! - Credible sets with purity filtering (min_abs_corr / median_abs_corr)
//! - PIP computation with prior_tol trimming
//!
//! **Out of scope** (not ported): `susie_rss_lambda`, infinitesimal/ash
//! unmappable effects, NIG residual prior, R-mismatch / finite-reference
//! correction, multi-panel mixture, slot priors, refinement, trend filtering,
//! `mr.ash`, individual-level `susie()`/`susie_ss()`.
//!
//! ## Faithfulness
//!
//! - Linear algebra runs on [`faer`].
//! - `NA` is `f64::NAN`.
//! - The scalar prior-variance optimizer reproduces R `optim(method="Brent")`
//!   via a faithful Brent golden-section + successive-parabolic port.
//! - Cross-validated against 40 golden scenarios generated by `susieR` 0.16.6
//!   on the exact simulation seeds used by susieR's own reference tests.

