/// Errors produced by the SuSiE-RSS fitting procedure.
#[derive(Debug, Error)]
pub enum SusieError {
    #[error("z and R must have compatible lengths: z has {z_len}, R is {r_n}x{r_n}")]
    DimMismatch { z_len: usize, r_n: usize },

    #[error("R must be square")]
    RNotSquare,

    #[error("R must be symmetric")]
    RNotSymmetric,

    #[error("n must be greater than 1")]
    InvalidN,

    #[error("shat must be positive")]
    InvalidShat,

    #[error("Input z and (bhat, shat) are mutually exclusive")]
    AmbiguousInput,

    #[error("Either z or (bhat, shat) must be provided")]
    MissingInput,

    #[error("L must be at least 1")]
    InvalidL,

    #[error("coverage must be in (0, 1)")]
    InvalidCoverage,

    #[error("ELBO became infinite during fitting")]
    InfiniteElbo,

    #[error(transparent)]
    Json(#[from] serde_json::Error),
}

// ─── numerics helpers shared across modules ─────────────────────────────────

/// Machine epsilon, matching R's `.Machine$double.eps`.
pub(crate) const EPS: f64 = f64::EPSILON;

/// sqrt(.Machine$double.eps) ≈ 1.49e-8 — used as a stabilizer in log-space.
pub(crate) const SQRT_EPS: f64 = 1.4901161193847656e-8;

/// Numerically stable log-sum-exp of a slice.
#[inline]
pub(crate) fn log_sum_exp(vals: &[f64]) -> f64 {
    if vals.is_empty() {
        return f64::NEG_INFINITY;
    }
    let m = vals.iter().copied().fold(f64::NEG_INFINITY, f64::max);
    if m == f64::NEG_INFINITY {
        return f64::NEG_INFINITY;
    }
    let s: f64 = vals.iter().map(|&v| (v - m).exp()).sum();
    m + s.ln()
}

// ─── public entry point ──────────────────────────────────────────────────────

/// Fit SuSiE from GWAS regression summary statistics.
///
/// This is the Rust analogue of `susieR::susie_rss(z=, R=, n=, ...)`.
///
/// See [`RssInput`] for the full parameter set and [`SusieFit`] for the
/// returned model.
pub fn susie_rss(input: &RssInput) -> Result<SusieFit, SusieError> {
    let (data, mut params) = data::build_rss_data(input)?;
    model::fit(&data, &mut params)
}
